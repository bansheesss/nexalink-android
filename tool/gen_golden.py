#!/usr/bin/env python3
"""Generate golden test vectors from the ViunaLink Windows reference implementation.

    python tool/gen_golden.py --repo ../nexalink-windows --out test/vectors/golden.json

The Windows repo is the source of truth: handshake bytes, encrypted frames,
message packers, file-transfer replies, filename sanitising and discovery
packets are all produced by running its actual modules (with fixed keys/salt).
Output is deterministic, so CI can regenerate it and diff against the
committed copy to detect protocol drift.
"""
from __future__ import annotations

import argparse
import asyncio
import hashlib
import hmac
import json
import os
import struct
import sys
import tempfile
from pathlib import Path
from unittest import mock

SEED_C = bytes(range(0, 32))
SEED_H = bytes(range(32, 64))
SALT = bytes(range(100, 116))
PASSWORD = "Abcd1234xy"
WRONG = "wrongpass"
REAL_URANDOM = os.urandom


# ---- in-memory byte pipe so the REAL Connection/handshake code can run ----
class _Reader:
    def __init__(self):
        self.buf, self.ev, self.eof = bytearray(), asyncio.Event(), False

    def feed(self, data):
        self.buf += data
        self.ev.set()

    async def readexactly(self, n):
        while len(self.buf) < n:
            if self.eof:
                raise asyncio.IncompleteReadError(bytes(self.buf), n)
            self.ev.clear()
            await self.ev.wait()
        out = bytes(self.buf[:n])
        del self.buf[:n]
        return out


class _Writer:
    def __init__(self, peer: _Reader, log: list):
        self.peer, self.log = peer, log

    def write(self, data):
        self.log.append(bytes(data))
        self.peer.feed(data)

    async def drain(self):
        pass

    def get_extra_info(self, name, default=None):
        return None

    def close(self):
        self.peer.eof = True
        self.peer.ev.set()

    async def wait_closed(self):
        pass


def hkdf_mirror(ikm: bytes, salt: bytes, info: bytes, length: int) -> bytes:
    """RFC 5869 written exactly like the Dart implementation."""
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:length]


async def run_handshake(core, client_pw: str, host_pw: str):
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
    net, sec = core["network"], core["security"]
    ra, rb = _Reader(), _Reader()
    log_c, log_h = [], []
    client = net.Connection(ra, _Writer(rb, log_c))
    host = net.Connection(rb, _Writer(ra, log_h))
    keys = iter([X25519PrivateKey.from_private_bytes(SEED_C),
                 X25519PrivateKey.from_private_bytes(SEED_H)])
    fake = lambda n: SALT if n == 16 else REAL_URANDOM(n)
    with mock.patch.object(sec, "new_ephemeral", lambda: next(keys)), \
            mock.patch.object(os, "urandom", fake):
        res = await asyncio.gather(net.client_handshake(client, client_pw),
                                   net.host_handshake(host, host_pw),
                                   return_exceptions=True)
    return client, host, log_c, log_h, res


def strip(frame: bytes) -> bytes:
    (n,) = struct.unpack("!I", frame[:4])
    assert n == len(frame) - 4
    return frame[4:]


async def build(core, tmp: Path) -> dict:
    sec, proto, net = core["security"], core["protocol"], core["network"]
    from cryptography.hazmat.primitives.asymmetric.x25519 import (
        X25519PrivateKey, X25519PublicKey)
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    MT = proto.MsgType
    out: dict = {"meta": {"protocol_version": proto.PROTOCOL_VERSION,
                          "note": "generated by tool/gen_golden.py from the Python reference"}}

    # ---------------- primitives ----------------
    pc, ph = X25519PrivateKey.from_private_bytes(SEED_C), X25519PrivateKey.from_private_bytes(SEED_H)
    pub_c, pub_h = sec.public_bytes(pc), sec.public_bytes(ph)
    shared = pc.exchange(X25519PublicKey.from_public_bytes(pub_h))
    assert shared == ph.exchange(X25519PublicKey.from_public_bytes(pub_c))
    pw_key = sec.derive_password_key(PASSWORD, SALT)
    out["primitives"] = {
        "scrypt": {"password": PASSWORD, "salt": SALT.hex(), "n": 32768, "r": 8, "p": 1,
                   "key": pw_key.hex()},
        "x25519": {"client_seed": SEED_C.hex(), "client_pub": pub_c.hex(),
                   "host_seed": SEED_H.hex(), "host_pub": pub_h.hex(), "shared": shared.hex()},
    }

    # ---------------- successful handshake (real code, fixed randomness) ----
    client, host, log_c, log_h, res = await run_handshake(core, PASSWORD, PASSWORD)
    assert res == [None, 0], res  # client completes; Windows host returns the matched password index (0)
    hello, proof = strip(log_c[0]), strip(log_c[1])
    ack, ok = strip(log_h[0]), strip(log_h[1])
    transcript = hashlib.sha256(hello + ack).digest()
    ikm = shared + pw_key
    okm = hkdf_mirror(ikm, transcript, b"remotelink/v1", 96)
    c2h, h2c, auth = okm[:32], okm[32:64], okm[64:]
    # the Dart-style HKDF must equal the library one used by the repo
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.kdf.hkdf import HKDF
    assert HKDF(hashes.SHA256(), 96, salt=transcript, info=b"remotelink/v1").derive(ikm) == okm
    assert json.loads(ok)["proof"] == hmac.new(auth, b"host", hashlib.sha256).hexdigest()
    assert json.loads(proof)["proof"] == hmac.new(auth, b"client", hashlib.sha256).hexdigest()
    out["primitives"]["hkdf"] = {"ikm": ikm.hex(), "salt": transcript.hex(),
                                 "info": "remotelink/v1", "okm": okm.hex()}
    out["handshake_ok"] = {
        "password": PASSWORD, "salt": SALT.hex(),
        "client_seed": SEED_C.hex(), "host_seed": SEED_H.hex(),
        "client_to_host": [log_c[0].hex(), log_c[1].hex()],
        "host_to_client": [log_h[0].hex(), log_h[1].hex()],
        "transcript": transcript.hex(),
        "keys": {"c2h": c2h.hex(), "h2c": h2c.hex(), "auth": auth.hex()},
    }

    # ---------------- encrypted session frames ----------------
    c2h_msgs = [
        (MT.PING, struct.pack("!d", 123.456)),
        (MT.MOUSE_MOVE, proto.pack_mouse_move(0.5, 0.25)),
        (MT.MOUSE_BUTTON, proto.pack_mouse_button(1, True)),
        (MT.MOUSE_SCROLL, proto.pack_scroll(0, -1)),
        (MT.KEY, proto.pack_key("a", True)),
        (MT.KEY, proto.pack_key("س", False)),
        (MT.FRAME_REQUEST, proto.pack_json({"quality": 45, "monitor": 2, "keyframe": True})),
        (MT.CLIPBOARD, "سلام hello".encode()),
        (MT.BYE, b""),
    ]
    h2c_msgs = [
        (MT.SESSION_INFO, proto.pack_json({"width": 1920, "height": 1080, "os": "linux",
                                           "codec": "jpeg", "name": "box", "monitor": 1,
                                           "monitors": [{"index": 0, "width": 1920, "height": 1080,
                                                         "left": 0, "top": 0}]})),
        (MT.FRAME, proto.Frame(7, 1234, proto.Codec.JPEG, 1920, 1080, b"\xff\xd8fakejpeg\xff\xd9").pack()),
        (MT.PONG, struct.pack("!d", 123.456)),
        (MT.CLIPBOARD, "from host".encode()),
        (MT.ERROR, proto.pack_json({"reason": "Host is busy"})),
    ]
    frames = {"client_to_host": [], "host_to_client": []}
    for t, b in c2h_msgs:
        await client.send(t, b)
        frames["client_to_host"].append({"type": int(t), "body": b.hex(), "wire": log_c[-1].hex()})
        assert await host.recv() == (t, b)
    for t, b in h2c_msgs:
        await host.send(t, b)
        frames["host_to_client"].append({"type": int(t), "body": b.hex(), "wire": log_h[-1].hex()})
        assert await client.recv() == (t, b)
    # independent re-derivation of the first frame from raw primitives
    first = frames["client_to_host"][0]
    plain = bytes([first["type"]]) + bytes.fromhex(first["body"])
    hdr = struct.pack("!I", len(plain) + 16)
    nonce = b"\x00" * 4 + (0).to_bytes(8, "big")
    assert hdr + AESGCM(c2h).encrypt(nonce, plain, hdr) == bytes.fromhex(first["wire"])
    out["session_frames"] = frames

    # ---------------- wrong password ----------------
    _, _, lc, lh, res = await run_handshake(core, WRONG, PASSWORD)
    assert isinstance(res[0], sec.AuthError) and isinstance(res[1], sec.AuthError), res
    assert json.loads(strip(lh[1])) == {"ok": False}
    out["handshake_bad_password"] = {
        "password": WRONG, "salt": SALT.hex(),
        "client_seed": SEED_C.hex(), "host_seed": SEED_H.hex(),
        "client_to_host": [x.hex() for x in lc], "host_to_client": [x.hex() for x in lh]}

    # ---------------- message packers ----------------
    P = proto
    msgs = []
    for nx, ny in ((0.5, 0.25), (0.0, 1.0), (1.5, -0.2), (0.123456, 0.987654)):
        msgs.append({"kind": "mouse_move", "nx": nx, "ny": ny, "hex": P.pack_mouse_move(nx, ny).hex()})
    for b, p in ((1, True), (2, False), (3, True)):
        msgs.append({"kind": "mouse_button", "button": b, "pressed": p, "hex": P.pack_mouse_button(b, p).hex()})
    for dx, dy in ((0, -1), (3, 120), (-5, 0)):
        msgs.append({"kind": "scroll", "dx": dx, "dy": dy, "hex": P.pack_scroll(dx, dy).hex()})
    for n, p in (("a", True), ("enter", False), ("س", True), ("page_down", True)):
        msgs.append({"kind": "key", "name": n, "pressed": p, "hex": P.pack_key(n, p).hex()})
    for fid, ts, codec, w, h, data in ((1, 0, P.Codec.JPEG, 800, 600, b"abc"),
                                       (4000000000, 4294967295, P.Codec.WEBP, 3840, 2160, b"")):
        msgs.append({"kind": "frame", "frame_id": fid, "ts": ts, "codec": int(codec), "w": w, "h": h,
                     "data": data.hex(), "hex": P.Frame(fid, ts, codec, w, h, data).pack().hex()})
    for obj in ({"quality": 45, "monitor": 2, "keyframe": True},
                {"fps": 30, "scale": 0.75}, {"id": 3, "ok": False, "reason": "declined"}):
        msgs.append({"kind": "json", "args": obj, "hex": P.pack_json(obj).hex()})
    out["messages"] = msgs
    out["limits"] = {"max_handshake_size": P.MAX_HANDSHAKE_SIZE, "max_frame_size": P.MAX_FRAME_SIZE}

    # ---------------- file transfer (real FileTransfer, scripted peer) ----------------
    FT, Services = core["filetransfer"].FileTransfer, core["services"].Services

    class Rec:
        def __init__(self):
            self.sent, self.hook = [], None

        async def send(self, t, body=b""):
            self.sent.append((int(t), bytes(body)))
            if self.hook:
                self.hook(int(t), bytes(body))

    def summarize(sent):
        res = []
        for t, b in sent:
            if t == int(MT.FILE_CHUNK):
                res.append({"type": t, "id": struct.unpack("!I", b[:4])[0], "len": len(b) - 4,
                            "sha256": hashlib.sha256(b[4:]).hexdigest()})
            else:
                res.append({"type": t, "body": b.hex()})
        return res

    data = bytes((i * 7 + 3) % 256 for i in range(300000))
    path = tmp / "payload.bin"
    path.write_bytes(data)
    rec = Rec()
    ft = FT(rec, Services(dest_dir=tmp / "unused"), 1)

    def hook(t, body):
        loop = asyncio.get_running_loop()
        fid = json.loads(body)["id"] if t in (int(MT.FILE_OFFER), int(MT.FILE_DONE)) else None
        if t == int(MT.FILE_OFFER):
            loop.create_task(ft.handle(MT.FILE_ACCEPT, P.pack_json({"id": fid, "ok": True, "reason": ""})))
        elif t == int(MT.FILE_DONE):
            loop.create_task(ft.handle(MT.FILE_DONE, P.pack_json({"id": fid, "ok": True})))
    rec.hook = hook
    assert await ft.send_file(path) is True
    out["filetransfer_sender"] = {
        "filename": "payload.bin", "size": len(data),
        "content_rule": "byte[i] = (i*7+3) % 256", "id_parity": 1,
        "sent": summarize(rec.sent)}

    async def receiver(name, incoming, ask=None, max_bytes=None):
        dest = tmp / ("rx_" + name)
        rec = Rec()
        async def ask_fn(title, text):
            return ask
        svc = Services(dest_dir=dest, ask=ask_fn if ask is not None else None)
        if max_bytes is not None:
            svc.max_file_bytes = max_bytes
        ft = FT(rec, svc, 0)
        for t, b in incoming:
            await ft.handle(t, b)
            await asyncio.sleep(0.05)
        saved = sorted(p.name for p in dest.glob("*")) if dest.exists() else []
        return {"name": name, "ask": ask, "max": max_bytes,
                "incoming": [{"type": int(t), "body": b.hex()} for t, b in incoming],
                "expected_sent": summarize(rec.sent), "saved": saved}

    hello5 = hashlib.sha256(b"hello").hexdigest()
    chunk = lambda fid, d: struct.pack("!I", fid) + d
    offer = lambda fid, n, size: (MT.FILE_OFFER, P.pack_json({"id": fid, "name": n, "size": size}))
    done = lambda fid, sha: (MT.FILE_DONE, P.pack_json({"id": fid, "sha256": sha}))
    out["filetransfer_receiver"] = [
        await receiver("ok", [offer(2, "a/b/../evil?.txt", 5), (MT.FILE_CHUNK, chunk(2, b"hello")),
                              done(2, hello5)]),
        await receiver("declined", [offer(2, "x.txt", 5)], ask=False),
        await receiver("toolarge", [offer(2, "x.txt", 11)], max_bytes=10),
        await receiver("badhash", [offer(4, "y.txt", 5), (MT.FILE_CHUNK, chunk(4, b"hello")),
                                   done(4, "00" * 32)]),
    ]
    fnames = ["../../etc/passwd", "C:\\x\\evil?.exe", "CON.txt", "...", "normal.txt",
              "a/b/c.txt", "  .hidden", "name with spaces .txt", "dir/", "a" * 300 + ".txt", "سلام.txt"]
    out["safe_names"] = [{"in": n, "out": core["filetransfer"].safe_name(n)} for n in fnames]

    # ---------------- discovery ----------------
    D = core["discovery"]
    sent = []
    class T:
        def sendto(self, data, addr):
            sent.append(data)
    resp = D._Responder({"id": "987654321", "name": "box", "port": 7070})
    resp.connection_made(T())
    cases = []
    for q in (b"RLK1?987654321", b"RLK1?*", b"RLK1?", b"RLK1?111111111", b"junk", b"RLK1!x"):
        sent.clear()
        resp.datagram_received(q, ("1.2.3.4", 7071))
        cases.append({"query": q.hex(), "reply": sent[0].hex() if sent else None})
    out["discovery"] = {"port": D.DISCOVERY_PORT, "magic": D.MAGIC.decode(),
                        "query_for_id": (D.MAGIC + b"?" + b"987654321").hex(),
                        "query_any": (D.MAGIC + b"?*").hex(), "responder_cases": cases}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="path to nexalink-windows checkout")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sys.path.insert(0, str(Path(a.repo).resolve()))
    import importlib
    core = {n: importlib.import_module(f"core.{n}") for n in
            ("network", "security", "protocol", "filetransfer", "services", "discovery")}
    with tempfile.TemporaryDirectory() as td:
        data = asyncio.run(build(core, Path(td)))
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(data, indent=1, ensure_ascii=True) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
